"""Mixed-signal stimulus: Verilog control logic -> SPICE PWL sources.

``Testbench.digital`` declares a *self-contained* Verilog block plus a
list of ``{verilog_net, node, vhi, vlo, delay}`` mappings. This module
compiles the rtl with Icarus Verilog, runs it under vvp with a generated
dump bench (``_dump_tb.v``), parses the per-net transition dump and
converts each listed net into a piecewise-linear voltage source card
(``V_dig_<node> <node> 0 PWL(<t> <v> ... r 0)``) that
``simulate_auto``/``simulate_extracted`` splice into the deck in place of
the auto-bias source for that node.

**RTL contract** (documented in docs/USAGE.md):

- ``digital.rtl`` must contain exactly one *top* module — a module no
  other module instantiates; it is instantiated unconnected as ``dut``
  by the generated bench, so ports are legal but left floating.
- The rtl must drive itself: its own ``initial``/``always`` clock and
  its own ``$finish`` — the wrapper adds **no** stimulus. If the rtl
  never finishes, a watchdog (``_WATCHDOG_S``, default 20 µs of sim
  time) stops the dump; ``stopped_by`` reports which path ended it.
- ``digital.timescale`` is prepended as a `` `timescale`` directive to
  the written rtl file *and* the dump bench, so a rtl with no directive
  of its own gets deterministic delay units (a rtl that declares its own
  keeps it — directives later in the file win). Dump timestamps are in
  ``timescale``'s unit field and converted to seconds for the PWL.
- ``verilog_net`` may name any net/reg reachable hierarchically from the
  top (``count``, ``count[0]``, ``sub.q``). It is digitised: ``0`` →
  ``vlo``, any nonzero → ``vhi`` — use bit-selects for buses. ``x``/``z``
  samples hold the previous defined level (``vlo`` before the first) and
  are counted under ``unknown_samples`` — never silently invented.

Fail-closed: no iverilog runner → ``unavailable`` with every route
tried; compile/elaboration failure or a nonzero vvp exit → ``error``
with the tool's own message; a listed net that produces no dump lines →
``error`` naming it (a source that drives nothing silently is forbidden).
"""

from __future__ import annotations

import math
import re
import tempfile
from pathlib import Path
from typing import Any

from layout_canvas.ir.model import DigitalStimulus, Testbench
from layout_canvas.tools import verilog

# Sim-time bound (seconds) for rtls that never call $finish.
_WATCHDOG_S = 20e-6

_TIMESCALE_RE = re.compile(
    r"^\s*(\d+(?:\.\d+)?)\s*(fs|ps|ns|us|ms|s)\s*/"
    r"\s*(\d+(?:\.\d+)?)\s*(fs|ps|ns|us|ms|s)\s*$")
_UNIT_S = {"fs": 1e-15, "ps": 1e-12, "ns": 1e-9, "us": 1e-6,
           "ms": 1e-3, "s": 1.0}

_COMMENT_RE = re.compile(r"//[^\n]*|/\*.*?\*/", re.DOTALL)
_MODULE_RE = re.compile(r"\bmodule\s+([A-Za-z_][A-Za-z0-9_]*)")

_DUMP_PREFIX = "LC_DUMP"
_END_PREFIX = "LC_END"


def _timescale_seconds(timescale: str) -> float | None:
    """Seconds per timescale *unit* (the left field of '1ns/1ps')."""
    m = _TIMESCALE_RE.match(timescale)
    if not m:
        return None
    return float(m.group(1)) * _UNIT_S[m.group(2)]


def _top_module(rtl: str) -> str | None:
    """The rtl's top: the unique declared module no other module
    instantiates. ``None`` when there is none or the choice is ambiguous."""
    text = _COMMENT_RE.sub("", rtl)
    names = _MODULE_RE.findall(text)
    if not names:
        return None
    instantiated = set()
    for name in set(names):
        if re.search(
                rf"^\s*{re.escape(name)}\s*(#\s*\(|"
                rf"[A-Za-z_][A-Za-z0-9_$]*\s*\()",
                text, re.MULTILINE):
            instantiated.add(name)
    roots = [n for n in dict.fromkeys(names) if n not in instantiated]
    return roots[0] if len(roots) == 1 else None


def _dump_bench(module: str, nets: list[str], timescale: str,
                watchdog_units: int) -> str:
    """The generated ``_dump_tb.v``: instantiate the user top unconnected,
    snapshot every listed net at t=0 (so flat nets enter the dump too),
    then ``always @(dut.<net>)`` for event-accurate transitions. Lines are
    ``LC_DUMP <t> <net> <value>`` (``$realtime`` in timescale units) plus a
    final ``LC_END <t>`` marker from the watchdog."""
    lines = [
        f"`timescale {timescale}",
        "// Generated by layout-canvas tools/mixed_signal.py — dump bench.",
        "// Instantiates the user top unconnected and logs each listed net.",
        "module _dump_tb;",
        f"    {module} dut ();",
        "    initial begin",
        "        #0;",
    ]
    for net in nets:
        lines.append(
            f'        $display("{_DUMP_PREFIX} %0.9g {net} %0d", '
            f"$realtime, dut.{net});")
    lines.append("    end")
    for net in nets:
        lines.append(f"    always @(dut.{net})")
        lines.append(
            f'        $display("{_DUMP_PREFIX} %0.9g {net} %0d", '
            f"$realtime, dut.{net});")
    lines += [
        "    // watchdog: bound runaway rtls that never $finish",
        "    initial begin",
        f"        #{watchdog_units};",
        f'        $display("{_END_PREFIX} %0.9g", $realtime);',
        "        $finish;",
        "    end",
        "endmodule",
        "",
    ]
    return "\n".join(lines)


def _parse_dump(text: str, unit_s: float
                ) -> tuple[dict[str, list[tuple[float, Any]]],
                           float | None, int]:
    """``LC_DUMP <t> <net> <val>`` -> {net: [(t_seconds, val)]} (deduped
    per (net, t), last write wins), plus the ``LC_END`` marker time and
    the number of dump lines consumed. ``val`` is an int for defined
    values, the raw ``x``/``z`` token otherwise."""
    series: dict[str, list[tuple[float, Any]]] = {}
    end_t: float | None = None
    n_lines = 0
    for line in text.splitlines():
        parts = line.split()
        if not parts or parts[0] not in (_DUMP_PREFIX, _END_PREFIX):
            continue
        if parts[0] == _END_PREFIX:
            if len(parts) >= 2:
                try:
                    end_t = float(parts[1]) * unit_s
                except ValueError:
                    pass
            continue
        if len(parts) < 4:
            continue
        n_lines += 1
        try:
            t = float(parts[1]) * unit_s
        except ValueError:
            continue
        net, raw = parts[2], parts[3].lower()
        try:
            val: Any = int(raw)
        except ValueError:
            val = raw  # "x"/"z" (or a b-format token) — kept, not faked
        lst = series.setdefault(net, [])
        if lst and lst[-1][0] == t:
            lst[-1] = (t, val)
        else:
            lst.append((t, val))
    return series, end_t, n_lines


def _pwl_pairs(net_series: list[tuple[float, Any]],
               vhi: float, vlo: float, delay: float,
               end_t: float | None) -> tuple[list[tuple[float, float]], int]:
    """Digitise a (t, logic) series into stepwise PWL ``(t_seconds, V)``
    pairs — a level change at ``t`` emits ``(t+delay, v_prev)`` then
    ``(t+delay, v_new)`` so edges are vertical (ngspice accepts repeated
    timestamps). ``x``/``z`` hold the previous defined level (``vlo``
    before the first) and are counted. A trailing ``(end_t+delay, last)``
    fixes the repeat period at the dump's end."""
    pts: list[tuple[float, float]] = []
    cur: float | None = None
    unknown = 0
    for t, v in net_series:
        if isinstance(v, int):
            volt = vhi if v != 0 else vlo
        else:
            unknown += 1
            volt = cur if cur is not None else vlo
        tt = t + delay
        if not pts:
            pts.append((tt, volt))
        elif volt != cur:
            pts.append((tt, cur if cur is not None else vlo))
            pts.append((tt, volt))
        else:
            pts[-1] = (tt, volt)
        cur = volt
    if end_t is not None and pts:
        te = end_t + delay
        if te > pts[-1][0]:
            pts.append((te, cur if cur is not None else vlo))
    return pts, unknown


def _source_line(node: str, pairs: list[tuple[float, float]]) -> str:
    """The literal source card: constant waveforms become a DC value,
    toggling ones a repeating PWL (``r 0`` — repeat from t=0; the period
    is the last pair's time)."""
    elem = re.sub(r"[^A-Za-z0-9_]", "_", node)
    if len({v for _, v in pairs}) == 1:
        return f"V_dig_{elem} {node} 0 {pairs[0][1]:g}"
    pts = " ".join(f"{t:.9g} {v:g}" for t, v in pairs)
    return f"V_dig_{elem} {node} 0 PWL({pts} r 0)"


def _fail(status: str, reason: str, **extra: Any) -> dict[str, Any]:
    out = {"status": status, "reason": reason, "sources": {},
           "lines": {}, "series": {}, "raw_dump_lines": 0}
    out.update(extra)
    return out


def digital_stimulus(tb: Testbench, *, executable: str | None = None,
                     timeout: int = 60,
                     workdir: str | Path | None = None) -> dict[str, Any]:
    """Compile + run ``tb.digital`` and build PWL source cards per node.

    Returns ``{status: ok|unavailable|error, reason, sources: {node:
    [(t, v), ...]}, lines: {node: "<V card>"}, series: {verilog_net:
    [(t, val)]}, raw_dump_lines, runner, workdir, ...}``. Runner
    discovery is shared with ``tools/verilog.py`` (``executable`` /
    ``LAYOUT_CANVAS_IVERILOG`` → PATH → ``wsl -d <distro>``).
    """
    dig: DigitalStimulus | None = tb.digital
    assert dig is not None, "digital_stimulus needs tb.digital"
    unit_s = _timescale_seconds(dig.timescale)
    if unit_s is None:
        return _fail("error",
                     "digital stimulus: cannot parse timescale "
                     f"{dig.timescale!r} (expected '<n><unit>/<n><unit>', "
                     "e.g. '1ns/1ps')")
    module = _top_module(dig.rtl)
    if module is None:
        return _fail("error",
                     "digital stimulus: cannot determine the rtl top "
                     "module — declare exactly one module that no other "
                     "module instantiates")

    candidates, tried = verilog._runner_candidates(executable)
    if not candidates:
        return _fail("unavailable",
                     "no verilog simulator (iverilog/vvp) — tried: "
                     + "; ".join(tried))

    # unique net names, declaration order
    nets = list(dict.fromkeys(s.verilog_net for s in dig.signals))
    root = Path(workdir) if workdir else Path(
        tempfile.mkdtemp(prefix="lc_mixed_"))
    root.mkdir(parents=True, exist_ok=True)
    rtl_path = root / f"{tb.name}_rtl.v"
    tb_path = root / "_dump_tb.v"
    out_path = root / "digital_stimulus.out"
    # The `timescale prelude gives a directive-less rtl deterministic
    # delay units; an rtl-declared directive still wins for its own text.
    rtl_path.write_text(f"`timescale {dig.timescale}\n{dig.rtl}",
                        encoding="utf-8")
    watchdog_units = max(1, int(math.ceil(_WATCHDOG_S / unit_s)))
    tb_path.write_text(
        _dump_bench(module, nets, dig.timescale, watchdog_units),
        encoding="utf-8")

    files = {"workdir": str(root), "rtl_path": str(rtl_path),
             "tb_path": str(tb_path), "image_path": str(out_path)}
    exec_failures: list[str] = []
    for cand in candidates:
        res = verilog._compile_and_run(
            cand, [rtl_path, tb_path], out_path, timeout)
        if res is None:
            exec_failures.append(f"{cand['label']} (did not execute)")
            continue
        if not res["compile_ok"]:
            return _fail(
                "error",
                f"iverilog compile failed ({cand['label']}): "
                f"{res['compile_output'].strip()}",
                runner=cand["label"], **files)
        if not res["vvp_ok"]:
            return _fail(
                "error",
                f"vvp run failed rc={res['vvp_rc']} ({cand['label']}): "
                f"{res['vvp_output'].strip()[:4000]}",
                runner=cand["label"], **files)

        series, end_t, n_lines = _parse_dump(res["vvp_output"], unit_s)
        missing = [net for net in nets if not series.get(net)]
        if missing:
            return _fail(
                "error",
                "digital signal(s) never appeared in the Verilog dump: "
                + ", ".join(f"{tb.name}.{n}" for n in missing)
                + " — check each verilog_net names a wire/reg under the "
                  "rtl top",
                runner=cand["label"], raw_dump_lines=n_lines, **files)

        stopped_by = "watchdog" if end_t is not None else "rtl"
        # The rtl's own $finish ends the run before the watchdog marker —
        # the dump end is then the latest timestamp seen.
        if end_t is None:
            end_t = max((lst[-1][0] for lst in series.values() if lst),
                        default=None)

        sources: dict[str, list[tuple[float, float]]] = {}
        lines: dict[str, str] = {}
        unknown: dict[str, int] = {}
        for sig in dig.signals:
            pts, n_unknown = _pwl_pairs(
                series[sig.verilog_net], sig.vhi, sig.vlo, sig.delay,
                end_t)
            sources[sig.node] = pts
            lines[sig.node] = _source_line(sig.node, pts)
            if n_unknown:
                unknown[sig.verilog_net] = n_unknown
        return {
            "status": "ok",
            "reason": f"iverilog compile + vvp dump clean "
                      f"({cand['label']})",
            "runner": cand["label"],
            "module": module,
            "sources": sources,
            "lines": lines,
            "series": series,
            "raw_dump_lines": n_lines,
            "end_time": end_t,
            "stopped_by": stopped_by,
            "unknown_samples": unknown,
            **files,
        }
    return _fail("unavailable",
                 "no verilog simulator candidate could execute — tried: "
                 + "; ".join(tried + exec_failures),
                 **files)
