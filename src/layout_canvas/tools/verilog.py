"""Verilog blackbox stub generation and Icarus Verilog lint (fail-closed).

``verilog_stub`` emits a passive blackbox module for a Block IR design:
every ``Design.ports`` entry becomes a port — ``input``/``output`` keep
their direction, everything else (``inout``, ``supply``, bidirectional,
unknown) degrades to ``inout`` — all ``wire``, no internal logic.  That
is the analog-correct convention: the stub only fixes the port contract
a digital wrapper or testbench can bind against.

``verilog_check`` lints the stub with Icarus Verilog: it writes the stub
plus a generated testbench that instantiates the module once with named
``.port()`` hookups (unconnected), then runs ``iverilog -o`` and ``vvp``.
Status comes only from real exit codes/stderr — ``unavailable`` names
every invocation route that was tried, never a fabricated pass.

Runner selection order:

1. ``executable=`` argument or ``LAYOUT_CANVAS_IVERILOG`` — a binary path
   or a full command prefix (e.g. ``wsl -d Ubuntu-24.04 iverilog``).  An
   explicit override is authoritative: if it does not resolve to a real
   binary/command the check is ``unavailable`` — a wrong configured path
   is surfaced, never silently bypassed.
2. ``iverilog`` on ``PATH``.
3. ``wsl -d <distro> iverilog`` when ``wsl`` exists — the distro is
   ``LAYOUT_CANVAS_WSL_DISTRO`` or the first ``wsl -l -q`` entry that is
   not ``docker-desktop*``.  Work files stay on the Windows side; paths
   are handed to WSL as ``/mnt/<drive>/...`` (drive letter lowercased,
   backslashes to slashes) — explicit translation, not ``wslpath``.
"""

from __future__ import annotations

import os
import re
import shlex
import shutil
import subprocess
import tempfile
from pathlib import Path
from typing import Any

from layout_canvas.ir.model import Design

IVERILOG_ENV = "LAYOUT_CANVAS_IVERILOG"
WSL_DISTRO_ENV = "LAYOUT_CANVAS_WSL_DISTRO"

# input/output keep their direction; anything else becomes inout.
_VERILOG_DIR = {"input": "input", "output": "output"}


def verilog_stub(design: Design, module_name: str | None = None) -> str:
    """Emit a passive blackbox Verilog module for ``design``.

    ``module_name`` defaults to the design name (IR names are already
    legal Verilog identifiers).  All ports are scalar ``wire``; analog
    pins carry no direction intent beyond input/output/inout.
    """
    module = module_name or design.name
    lines = [
        f"// Blackbox stub for design '{design.name}' (pdk: {design.pdk})",
        "// Generated by layout-canvas tools/verilog.py",
        "// Passive port list: no internal logic.",
        f"module {module} (",
    ]
    decls = []
    for port in design.ports:
        direction = _VERILOG_DIR.get(port.direction, "inout")
        decls.append(f"    {direction} wire {port.name}")
    lines.append(",\n".join(decls))
    lines.append(");")
    lines.append("endmodule")
    lines.append("")
    return "\n".join(lines)


def _lint_testbench(module: str, design: Design) -> str:
    """Minimal testbench: instantiate the blackbox once, ports unconnected."""
    hookups = ",\n        ".join(f".{p.name}()" for p in design.ports)
    return (
        "// Generated by layout-canvas tools/verilog.py — lint bench.\n"
        f"module tb_{module}_lint;\n"
        f"    {module} dut (\n        {hookups}\n    );\n"
        "endmodule\n"
    )


def verilog_check(design: Design, *, executable: str | None = None,
                  timeout: int = 60) -> dict[str, Any]:
    """Lint the design's blackbox stub with iverilog + vvp.

    Returns ``{"status": pass|fail|unavailable, "reason": str,
    "output": str}``.  ``pass`` needs both a clean ``iverilog -o``
    compile and a clean ``vvp`` run of the elaborated image.
    """
    module = design.name
    candidates, tried = _runner_candidates(executable)
    if not candidates:
        return {
            "status": "unavailable",
            "reason": "no usable iverilog — tried: " + "; ".join(tried),
            "output": "",
        }

    tmp = Path(tempfile.mkdtemp(prefix="lc_verilog_"))
    stub_path = tmp / f"{module}.v"
    tb_path = tmp / f"tb_{module}_lint.v"
    out_path = tmp / "lint.out"
    stub_path.write_text(verilog_stub(design), encoding="utf-8")
    tb_path.write_text(_lint_testbench(module, design), encoding="utf-8")

    exec_failures: list[str] = []
    for cand in candidates:
        res = _run_candidate(cand, stub_path, tb_path, out_path, timeout)
        if res is None:
            exec_failures.append(f"{cand['label']} (did not execute)")
            continue
        res.setdefault("runner", cand["label"])
        res.setdefault("workdir", str(tmp))
        return res
    return {
        "status": "unavailable",
        "reason": "no iverilog candidate could execute — tried: "
                  + "; ".join(tried + exec_failures),
        "output": "",
    }


# --- runner resolution ---------------------------------------------------


def _split_command(raw: str) -> list[str]:
    """Split a command prefix; an existing file path stays a single token."""
    if Path(raw).is_file():
        return [str(Path(raw))]
    try:
        parts = shlex.split(raw, posix=(os.name != "nt"))
    except ValueError:
        return [raw]
    if os.name == "nt":
        # posix=False keeps quotes on tokens — strip them so a quoted
        # path like '"C:\\a b\\iverilog.exe"' resolves as a file.
        parts = [p.strip("\"'") for p in parts]
    return parts


def _executable_ok(argv0: str) -> bool:
    if Path(argv0).is_file():
        return True
    # bare command name — must resolve on PATH (or be 'wsl' itself)
    if os.path.sep not in argv0 and "/" not in argv0 and "\\" not in argv0:
        return shutil.which(argv0) is not None
    return False


def _is_wsl_argv(argv: list[str]) -> bool:
    return Path(argv[0]).name.lower() in ("wsl", "wsl.exe")


def _vvp_for(argv: list[str], via_wsl: bool) -> list[str]:
    """Companion vvp prefix for an iverilog prefix."""
    if via_wsl:
        return [*argv[:-1], "vvp"]
    head = argv[0]
    p = Path(head)
    if p.is_file():
        for sib in (p.with_name("vvp"), p.with_name("vvp.exe")):
            if sib.is_file():
                return [str(sib), *argv[1:]]
    found = shutil.which("vvp")
    return [found or "vvp", *argv[1:]]


def _first_wsl_distro(timeout: int = 15) -> str | None:
    """First ``wsl -l -q`` entry that is not a docker-desktop distro.

    ``wsl -l -q`` writes UTF-16-LE without a BOM on Windows.
    """
    try:
        proc = subprocess.run(["wsl", "-l", "-q"], capture_output=True,
                              timeout=timeout, check=False)
    except (OSError, subprocess.TimeoutExpired):
        return None
    raw = proc.stdout
    text = raw.decode("utf-16-le", errors="ignore") if b"\x00" in raw \
        else raw.decode(errors="ignore")
    for line in text.replace("\x00", "").replace("\ufeff", "").splitlines():
        name = line.strip().strip("\x00")
        if name and "docker" not in name.lower():
            return name
    return None


def _runner_candidates(executable: str | None) -> tuple[list[dict], list[str]]:
    """(candidates, tried-notes). A candidate: argv prefixes + wsl flag."""
    cands: list[dict] = []
    tried: list[str] = []

    raw = executable if executable is not None else os.environ.get(IVERILOG_ENV)
    label = "executable" if executable is not None else IVERILOG_ENV
    if raw:
        argv = _split_command(raw)
        if argv and _executable_ok(argv[0]):
            wsl = _is_wsl_argv(argv)
            cands.append({"argv": argv, "vvp": _vvp_for(argv, wsl),
                          "wsl": wsl, "label": f"{label}={raw}"})
        else:
            tried.append(f"{label}={raw} (not found)")
        # An explicit override is the selection: do not probe further.
        return cands, tried

    found = shutil.which("iverilog")
    if found:
        argv = [found]
        cands.append({"argv": argv, "vvp": _vvp_for(argv, False),
                      "wsl": False, "label": f"PATH:{found}"})
    else:
        tried.append("iverilog on PATH")

    if shutil.which("wsl") or shutil.which("wsl.exe"):
        distro = os.environ.get(WSL_DISTRO_ENV) or _first_wsl_distro()
        if distro:
            argv = ["wsl", "-d", distro, "iverilog"]
            cands.append({"argv": argv, "vvp": ["wsl", "-d", distro, "vvp"],
                          "wsl": True, "label": f"wsl -d {distro}"})
        else:
            tried.append("wsl (no non-docker-desktop distro)")
    else:
        tried.append("wsl")
    return cands, tried


# --- execution ------------------------------------------------------------


def _wsl_path(path: Path) -> str:
    """Windows path -> ``/mnt/<drive>/...`` for a WSL-side command."""
    s = str(path).replace("\\", "/")
    m = re.match(r"^([A-Za-z]):/(.*)$", s)
    return f"/mnt/{m.group(1).lower()}/{m.group(2)}" if m else s


_EXEC_ERR = re.compile(
    r"not found|no such file|command not found|not recognized|"
    r"there is no distribution|unable to open input file",
    re.IGNORECASE)


def _exec_failed(proc: subprocess.CompletedProcess) -> bool:
    """True when the tool never really ran (missing binary/distro)."""
    return proc.returncode in (127, 255, 9009) or bool(
        _EXEC_ERR.search(proc.stderr or ""))


def _run_candidate(cand: dict, stub_path: Path, tb_path: Path,
                   out_path: Path, timeout: int) -> dict[str, Any] | None:
    """Run iverilog + vvp under one candidate. ``None`` = never executed."""
    def conv(p: Path) -> str:
        return _wsl_path(p) if cand["wsl"] else str(p)

    cmd = [*cand["argv"], "-o", conv(out_path), conv(stub_path),
           conv(tb_path)]
    try:
        comp = subprocess.run(cmd, capture_output=True, text=True,
                              timeout=timeout, check=False)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if _exec_failed(comp):
        return None
    output = comp.stdout + comp.stderr
    if comp.returncode != 0:
        return {"status": "fail", "reason": "iverilog compile failed",
                "output": output.strip()}
    if not out_path.is_file():
        return {"status": "fail",
                "reason": "iverilog produced no output image",
                "output": output.strip()}

    vcmd = [*cand["vvp"], conv(out_path)]
    try:
        run = subprocess.run(vcmd, capture_output=True, text=True,
                             timeout=timeout, check=False)
    except (OSError, subprocess.TimeoutExpired):
        return None
    output += run.stdout + run.stderr
    if _exec_failed(run):
        # vvp never ran (missing binary/distro) — another candidate may
        # still work; the check as a whole is unavailable if none do.
        return None
    if run.returncode != 0:
        return {"status": "fail", "reason": "vvp run failed",
                "output": output.strip()}
    return {"status": "pass",
            "reason": f"iverilog compile + vvp clean ({cand['label']})",
            "output": output.strip()}
